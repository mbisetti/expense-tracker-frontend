import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter } from 'react-router-dom';
import { AuthContext } from '../auth/context';
import { CategoryTransactionsModal } from './CategoryTransactionsModal';
import { jsonResponse } from '../../test/mockResponse';
import type { CategoryExpense } from './api';

// S51 (D9): la lupa. El desglose por subcategoría arriba de los movimientos, con filtro.

const base: CategoryExpense = {
  categoryId: 'cat-bol',
  name: 'Boliche',
  color: '#aa3bff',
  isEssential: false,
  amount: 100000,
  prevMonthAmount: 0,
  avg3mAmount: 0,
  txCount: 3,
  avg3mCount: 0,
  maxTxAmount: 50000,
};

const withSubs: CategoryExpense = {
  ...base,
  subcategories: [
    { subcategoryId: 'sub-tr', name: 'Transporte', amount: 50000, txCount: 1 },
    { subcategoryId: null, name: null, amount: 30000, txCount: 1 },
    { subcategoryId: 'sub-en', name: 'Entrada', amount: 20000, txCount: 1 },
  ],
};

const tx = (id: string, description: string, amount: number, subcategoryId: string | null) => ({
  id,
  accountId: 'acc-1',
  categoryId: 'cat-bol',
  subcategoryId,
  paymentMethodId: null,
  type: 'EXPENSE',
  amount,
  currency: 'ARS',
  exchangeRateAtTime: null,
  date: '2026-11-08',
  description,
  createdAt: '2026-11-08T00:00:00',
  recurringExpenseId: null,
  autoGenerated: false,
  sharedAmount: 0,
  shareCount: 0,
  pendingCount: 0,
  settledShareId: null,
  settledExpenseId: null,
  settledExpenseDescription: null,
});

const content = [
  tx('t1', 'uber', 50000, 'sub-tr'),
  tx('t2', 'barra', 30000, null),
  tx('t3', 'free', 20000, 'sub-en'),
];

beforeEach(() => {
  vi.stubGlobal(
    'fetch',
    vi.fn(() =>
      jsonResponse(200, { content, page: 0, size: 100, totalElements: content.length, totalPages: 1 }),
    ),
  );
});

afterEach(() => vi.unstubAllGlobals());

function renderModal(category: CategoryExpense) {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  render(
    <QueryClientProvider client={queryClient}>
      <AuthContext.Provider value={{ accessToken: 't', status: 'authenticated', setAccessToken: () => {} }}>
        <MemoryRouter>
          <CategoryTransactionsModal
            category={category}
            currency="ARS"
            year={2026}
            month={11}
            onClose={() => {}}
          />
        </MemoryRouter>
      </AuthContext.Provider>
    </QueryClientProvider>,
  );
}

describe('CategoryTransactionsModal: la lupa (S51)', () => {
  it('sin subcategorías no hay bloque, y la lista es la de siempre', async () => {
    renderModal(base);
    expect(await screen.findByText('uber')).toBeInTheDocument();
    expect(screen.queryByRole('region', { name: 'Por subcategoría' })).not.toBeInTheDocument();
    expect(screen.queryByText('Por subcategoría')).not.toBeInTheDocument();
  });

  it('con subcategorías lista los renglones con su porcentaje, incluido "Sin subcategoría"', async () => {
    renderModal(withSubs);
    const block = await screen.findByRole('region', { name: 'Por subcategoría' });
    const buttons = within(block).getAllByRole('button');
    expect(buttons.map((b) => b.textContent)).toEqual([
      expect.stringContaining('Transporte'),
      expect.stringContaining('Sin subcategoría'),
      expect.stringContaining('Entrada'),
    ]);
    expect(within(buttons[0]).getByText('50%')).toBeInTheDocument();
    expect(within(buttons[1]).getByText('30%')).toBeInTheDocument();
    expect(within(buttons[2]).getByText('20%')).toBeInTheDocument();
  });

  it('cada movimiento dice su subcategoría al lado de la fecha', async () => {
    renderModal(withSubs);
    await screen.findByText('uber');
    expect(screen.getByText(/· Transporte$/)).toBeInTheDocument();
    expect(screen.getByText(/· Entrada$/)).toBeInTheDocument();
  });

  it('tocar un renglón filtra la lista; tocarlo de nuevo la restaura', async () => {
    renderModal(withSubs);
    await screen.findByText('uber');
    const block = screen.getByRole('region', { name: 'Por subcategoría' });

    const transporte = within(block).getByRole('button', { name: /Transporte/ });
    fireEvent.click(transporte);
    expect(transporte).toHaveAttribute('aria-pressed', 'true');
    expect(screen.getByText('uber')).toBeInTheDocument();
    expect(screen.queryByText('barra')).not.toBeInTheDocument();
    expect(screen.queryByText('free')).not.toBeInTheDocument();

    fireEvent.click(within(block).getByRole('button', { name: /Sin subcategoría/ }));
    expect(screen.getByText('barra')).toBeInTheDocument();
    expect(screen.queryByText('uber')).not.toBeInTheDocument();

    fireEvent.click(within(block).getByRole('button', { name: /Sin subcategoría/ }));
    expect(screen.getByText('uber')).toBeInTheDocument();
    expect(screen.getByText('barra')).toBeInTheDocument();
    expect(screen.getByText('free')).toBeInTheDocument();
  });
});
