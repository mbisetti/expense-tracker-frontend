import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { AuthContext } from '../auth/context';
import { TransactionForm } from './TransactionForm';
import { ToastProvider } from '../../components/ui/ToastProvider';
import type { TransactionListItem } from './api';
import { jsonResponse } from '../../test/mockResponse';
import { selectOption, selectValue } from '../../test/selectOption';

// S51 (D10): el Select de subcategoría del form de movimientos.

const account = {
  id: 'acc-1',
  name: 'Efectivo',
  type: 'CASH',
  currency: 'ARS',
  balance: 100000,
  isInformal: false,
  statementCloseDay: null,
  paymentDueDay: null,
  balances: [{ currency: 'ARS', balance: 100000 }],
  createdAt: '2026-07-01T00:00:00',
};

const category = (id: string, name: string, subcategories?: { id: string; name: string }[]) => ({
  id,
  userId: 'user-1',
  name,
  type: 'EXPENSE',
  color: '#aa3bff',
  icon: null,
  isEssential: false,
  sourceDefaultCategoryId: null,
  createdAt: '2026-07-01T00:00:00',
  subcategories,
});

const boliche = category('cat-bol', 'Boliche', [
  { id: 'sub-tr', name: 'Transporte' },
  { id: 'sub-en', name: 'Entrada' },
]);
const comida = category('cat-com', 'Comida', []);
// Sin el campo: una respuesta (o un fixture) de antes de S51.
const viejo = category('cat-vie', 'Vieja');

const editTx: TransactionListItem = {
  id: 'tx-1',
  accountId: 'acc-1',
  categoryId: 'cat-bol',
  subcategoryId: 'sub-tr',
  paymentMethodId: null,
  type: 'EXPENSE',
  amount: 40000,
  currency: 'ARS',
  exchangeRateAtTime: null,
  date: '2026-11-08',
  description: 'uber',
  createdAt: '2026-11-08T00:00:00',
  recurringExpenseId: null,
  autoGenerated: false,
  sharedAmount: 0,
  shareCount: 0,
  pendingCount: 0,
  settledShareId: null,
  settledExpenseId: null,
  settledExpenseDescription: null,
};

let posts: Record<string, unknown>[];
let patches: Record<string, unknown>[];

beforeEach(() => {
  posts = [];
  patches = [];
  vi.stubGlobal(
    'fetch',
    vi.fn((url: string, options?: RequestInit) => {
      if (options?.method === 'POST') {
        const body = JSON.parse(options.body as string);
        posts.push(body);
        return jsonResponse(201, { ...editTx, ...body, id: 'tx-new', accountBalance: 60000 });
      }
      if (options?.method === 'PATCH') {
        const body = JSON.parse(options.body as string);
        patches.push(body);
        return jsonResponse(200, { ...editTx, ...body, accountBalance: 60000 });
      }
      if (String(url).includes('/categories')) return jsonResponse(200, [boliche, comida, viejo]);
      if (String(url).includes('/accounts')) return jsonResponse(200, [account]);
      return jsonResponse(200, []);
    }),
  );
});

afterEach(() => {
  vi.unstubAllGlobals();
});

function renderForm(transaction?: TransactionListItem) {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false }, mutations: { retry: false } },
  });
  render(
    <QueryClientProvider client={queryClient}>
      <AuthContext.Provider
        value={{ accessToken: 'test-token', status: 'authenticated', setAccessToken: () => {} }}
      >
        <ToastProvider>
          {transaction ? (
            <TransactionForm transaction={transaction} onClose={vi.fn()} />
          ) : (
            <TransactionForm onClose={vi.fn()} lockedType="EXPENSE" />
          )}
        </ToastProvider>
      </AuthContext.Provider>
    </QueryClientProvider>,
  );
}

describe('TransactionForm: subcategoría (S51)', () => {
  it('sin categoría, o con una que no tiene subcategorías, no hay Select', async () => {
    renderForm();
    await selectOption('Categoría', 'cat-com');
    expect(screen.queryByLabelText('Subcategoría')).not.toBeInTheDocument();
    await selectOption('Categoría', 'cat-vie');
    expect(screen.queryByLabelText('Subcategoría')).not.toBeInTheDocument();
  });

  it('aparece al elegir una categoría con subcategorías, y el alta la manda', async () => {
    renderForm();
    await selectOption('Cuenta', 'acc-1', { exact: false });
    await selectOption('Categoría', 'cat-bol');
    expect(selectValue('Subcategoría')).toBe('');
    await selectOption('Subcategoría', 'sub-en');

    fireEvent.change(screen.getByLabelText(/Monto/), { target: { value: '15000' } });
    fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));

    await waitFor(() => expect(posts).toHaveLength(1));
    expect(posts[0]).toMatchObject({ categoryId: 'cat-bol', subcategoryId: 'sub-en' });
  });

  it('sin elegir subcategoría, el alta no la manda', async () => {
    renderForm();
    await selectOption('Cuenta', 'acc-1', { exact: false });
    await selectOption('Categoría', 'cat-bol');
    fireEvent.change(screen.getByLabelText(/Monto/), { target: { value: '15000' } });
    fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));

    await waitFor(() => expect(posts).toHaveLength(1));
    expect(posts[0].subcategoryId).toBeUndefined();
  });

  it('cambiar de categoría la vuelve a "Sin subcategoría"', async () => {
    renderForm();
    await selectOption('Categoría', 'cat-bol');
    await selectOption('Subcategoría', 'sub-tr');
    await selectOption('Categoría', 'cat-com');
    await selectOption('Categoría', 'cat-bol');
    expect(selectValue('Subcategoría')).toBe('');
  });

  it('en edición arranca en la del movimiento, y pasar a "Sin subcategoría" manda ""', async () => {
    renderForm(editTx);
    await screen.findByLabelText('Subcategoría');
    await waitFor(() => expect(selectValue('Subcategoría')).toBe('sub-tr'));

    await selectOption('Subcategoría', '');
    fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));

    await waitFor(() => expect(patches).toHaveLength(1));
    expect(patches[0]).toEqual({ subcategoryId: '' });
  });

  it('en edición, sin tocarla, el PATCH no la manda', async () => {
    renderForm(editTx);
    await screen.findByLabelText('Subcategoría');
    fireEvent.change(screen.getByLabelText(/Monto/), { target: { value: '45000' } });
    fireEvent.click(screen.getByRole('button', { name: 'Guardar' }));

    await waitFor(() => expect(patches).toHaveLength(1));
    expect(patches[0]).toEqual({ amount: 45000 });
  });
});
