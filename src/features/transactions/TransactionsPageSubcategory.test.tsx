import { afterEach, describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter } from 'react-router-dom';
import { AuthContext } from '../auth/context';
import { ToastProvider } from '../../components/ui/ToastProvider';
import { TransactionsPage } from './TransactionsPage';
import { jsonResponse } from '../../test/mockResponse';

// S51 (D10): la fila de Movimientos dice "Boliche › Transporte" si el movimiento tiene
// subcategoría, y la categoría sola si no.

const account = { id: 'acc-1', name: 'Efectivo', type: 'CASH', currency: 'ARS', balance: 1000 };

const boliche = {
  id: 'cat-bol',
  userId: 'u1',
  name: 'Boliche',
  type: 'EXPENSE',
  color: '#aa3bff',
  icon: null,
  isEssential: false,
  sourceDefaultCategoryId: null,
  createdAt: '2026-07-01T00:00:00',
  subcategories: [{ id: 'sub-tr', name: 'Transporte' }],
};

const tx = (id: string, description: string, subcategoryId: string | null) => ({
  id,
  accountId: 'acc-1',
  categoryId: 'cat-bol',
  subcategoryId,
  paymentMethodId: null,
  type: 'EXPENSE',
  amount: 40000,
  currency: 'ARS',
  exchangeRateAtTime: null,
  date: '2026-11-08',
  description,
  createdAt: '2026-11-08T00:00:00',
  recurringExpenseId: null,
  autoGenerated: false,
  sharedAmount: 0,
  shareCount: 0,
  pendingCount: 0,
  settledShareId: null,
  settledExpenseId: null,
  settledExpenseDescription: null,
});

function stubFetch(content: unknown[]) {
  vi.stubGlobal(
    'fetch',
    vi.fn((url: string) => {
      if (url.includes('/categories')) return jsonResponse(200, [boliche]);
      if (url.includes('/transfers'))
        return jsonResponse(200, { content: [], page: 0, size: 100, totalElements: 0, totalPages: 1 });
      if (url.includes('/transactions'))
        return jsonResponse(200, {
          content,
          page: 0,
          size: 20,
          totalElements: content.length,
          totalPages: 1,
        });
      if (url.includes('/accounts')) return jsonResponse(200, [account]);
      return jsonResponse(200, []);
    }),
  );
}

function renderPage() {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  render(
    <QueryClientProvider client={queryClient}>
      <AuthContext.Provider value={{ accessToken: 't', status: 'authenticated', setAccessToken: () => {} }}>
        <ToastProvider>
          <MemoryRouter>
            <TransactionsPage />
          </MemoryRouter>
        </ToastProvider>
      </AuthContext.Provider>
    </QueryClientProvider>,
  );
}

afterEach(() => vi.unstubAllGlobals());

describe('TransactionsPage: subcategoría en la fila (S51)', () => {
  it('desktop: la columna Categoría dice "Boliche › Transporte" o "Boliche"', async () => {
    vi.stubGlobal('matchMedia', () => ({
      matches: true,
      addEventListener: () => {},
      removeEventListener: () => {},
    }));
    stubFetch([tx('t1', 'uber', 'sub-tr'), tx('t2', 'free', null)]);
    renderPage();

    expect(await screen.findByText('Boliche › Transporte')).toBeInTheDocument();
    // "Boliche" a secas también está en el filtro de categoría: se mira adentro de la fila.
    const freeRow = screen.getByText('free').closest('tr')!;
    expect(within(freeRow).getByText('Boliche')).toBeInTheDocument();
    expect(within(freeRow).queryByText(/›/)).not.toBeInTheDocument();
  });

  it('mobile: la sub-línea lleva la subcategoría', async () => {
    stubFetch([tx('t1', 'uber', 'sub-tr')]);
    renderPage();

    expect(await screen.findByText(/Boliche › Transporte/)).toBeInTheDocument();
  });
});
