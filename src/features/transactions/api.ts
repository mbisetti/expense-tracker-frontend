export type TransactionType = 'INCOME' | 'EXPENSE';

export type TransactionListItem = {
  id: string;
  accountId: string;
  categoryId: string | null;
  paymentMethodId: string | null;
  type: TransactionType;
  amount: number;
  currency: string;
  exchangeRateAtTime: number | null;
  date: string;
  description: string | null;
  createdAt: string;
  // Sprint 24.3: null = tx suelta; presente = vinculada a ese gasto recurrente.
  recurringExpenseId: string | null;
  // Sprint 24.4: true = la generó el débito automático (badge "Auto" en el feed y el historial).
  autoGenerated: boolean;
  // V36 "Hoy por vos, mañana por mí": parte del total que no es tuya. `amount` sigue siendo lo
  // que salió de la cuenta (por eso el feed reconcilia con el resumen bancario) y tu gasto real
  // es `amount - sharedAmount`. 0 = gasto normal.
  sharedAmount: number;
  // V36: cuánta gente participa y cuánta todavía no te pagó — el "(N restantes)" del feed.
  shareCount: number;
  pendingCount: number;
  // V36: esta tx es el cobro de una parte (plata que te devolvieron). No cuenta como ingreso.
  settledShareId: string | null;
  // V36: de qué gasto compartido vino ese cobro — permite explicar la fila y abrir su reparto.
  // Ambos null salvo en las filas de cobro.
  settledExpenseId: string | null;
  settledExpenseDescription: string | null;
};

export type TransactionResponse = TransactionListItem & {
  accountBalance: number;
};

export type PageResponse<T> = {
  content: T[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
};

export type TransactionFilters = {
  accountId?: string;
  categoryId?: string;
  paymentMethodId?: string;
  type?: TransactionType;
  /** Oculta las patas de transfer (feed unificado de Movimientos, Sprint 20 #4). */
  excludeTransferLegs?: boolean;
  /** Sprint 24.2: solo transacciones "Sin categoría" (category_id IS NULL). Mandar SOLO true;
   *  pasar undefined para apagado (buildTransactionsQuery serializaría "false"). */
  uncategorized?: boolean;
  /** Sprint 24.3: solo las vinculadas a este gasto recurrente (historial del detalle). */
  recurringExpenseId?: string;
  dateFrom?: string;
  dateTo?: string;
  search?: string;
  page?: number;
  size?: number;
  sort?: 'date' | 'amount';
  direction?: 'ASC' | 'DESC';
};

export function buildTransactionsQuery(filters: TransactionFilters): string {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(filters)) {
    if (value !== undefined && value !== null && value !== '') {
      params.set(key, String(value));
    }
  }
  const qs = params.toString();
  return qs ? `?${qs}` : '';
}
